void ValidateCgOperationResourceProfile(const CgOperationResourceProfile& p)
{
    const bool native=p.encoding==CgOperationVisualEncoding::NativeSevenState;
    if(p.encoding!=CgOperationVisualEncoding::NativeSevenState&&p.encoding!=CgOperationVisualEncoding::GuiSevenSlot)
        throw std::logic_error("Unknown CG operation visual encoding");
    if(p.pageCapacity<=0||p.popupPoints.size()!=static_cast<std::size_t>(p.pageCapacity)||p.digitResources.empty())
        throw std::logic_error("CG operation page/atlas spans are inconsistent");
    if(native)
    {
        if(p.nativePrimary.size()!=5||p.nativeCells.size()!=2||p.nativePages.size()!=2||
            !p.primaryButtons.empty()||!p.pageButtons.empty()||p.popupCellBackground||
            p.pagePolicy!=CgOperationPagePolicy::ClampedButtonsAndWheel)
            throw std::logic_error("Native CG operation records are incomplete");
        for(auto records:{p.nativePrimary,p.nativeCells,p.nativePages})for(const auto& record:records)
            for(int i=4;i<7;++i)if(record.namesAt00[i])
                throw std::logic_error("CG operation checked-state images are outside the audited input-mode0 contract");
    }
    else if(!p.nativePrimary.empty()||!p.nativeCells.empty()||!p.nativePages.empty()||
        p.primaryButtons.size()!=5||p.pageButtons.size()!=2||!p.popupCellBackground||
        p.pagePolicy!=CgOperationPagePolicy::WrappingButtons)
        throw std::logic_error("GUI CG operation records are incomplete");
    if(p.primaryFrame.eventAt00!=2||p.popupFrame.eventAt00!=8)
        throw std::logic_error("CG operation frame event contract is invalid");
    if(!native)
    {
        for(int i=0;i<5;++i)if(p.primaryButtons[i].common.eventAt00!=i+3)
            throw std::logic_error("CG operation primary action order is invalid");
        for(int i=0;i<2;++i)if(p.pageButtons[i].common.eventAt00!=i+10)
            throw std::logic_error("CG operation page action order is invalid");
        if(p.popupCell.common.eventAt00!=12)throw std::logic_error("CG operation cell event base is invalid");
    }
    for(const char* name:p.digitResources)if(!name)throw std::logic_error("CG operation atlas contains a null resource");
    for(const auto& mapping:p.digitSlots)for(int slot:mapping)
        if(slot<0||static_cast<std::size_t>(slot)>=p.digitResources.size())
            throw std::logic_error("CG operation digit mapping is outside the atlas");
    for(const auto& binding:p.navigation)
    {
        if(binding.mappings.size()!=static_cast<std::size_t>(p.pageCapacity+1)||
            binding.mappings.back().sourceEventValue!=-1)
            throw std::logic_error("CG operation navigation has no complete sentinel table");
    }
}
